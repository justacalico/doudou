import 'dart:convert';
import 'dart:io';

/// Builds the web dashboard in webui/ and rewrites
/// lib/server/webui_bundle.dart with the output embedded as base64 gzipped
/// files, so `doudou -server` can serve it from /app without any files on
/// disk. Run from the repository root after changing anything under webui/.
/// Pass --pack-only to re-embed the existing webui/build/web output without
/// rebuilding.
Future<void> main(List<String> args) async {
  final root = Directory.current;
  final webuiDir = Directory('${root.path}/webui');
  if (!webuiDir.existsSync()) {
    stderr.writeln('webui/ not found, run this from the repository root');
    exit(1);
  }

  if (!args.contains('--pack-only')) {
    final build = await Process.run(
      'flutter',
      ['build', 'web', '--release', '--base-href', '/app/',
        '--no-web-resources-cdn'],
      workingDirectory: webuiDir.path,
    );
    stdout.write(build.stdout);
    stderr.write(build.stderr);
    if (build.exitCode != 0) {
      exitCode = build.exitCode;
      return;
    }
  }

  final outDir = Directory('${webuiDir.path}/build/web');
  final files = <String, List<int>>{};
  for (final entity in outDir.listSync(recursive: true)) {
    if (entity is! File) continue;
    final rel = entity.path
        .substring(outDir.path.length + 1)
        .replaceAll(Platform.pathSeparator, '/');
    if (!_include(rel)) continue;
    files[rel] = await entity.readAsBytes();
  }

  for (final required in [
    'index.html',
    'flutter_bootstrap.js',
    'main.dart.js',
    'canvaskit/canvaskit.wasm',
    'canvaskit/chromium/canvaskit.wasm',
  ]) {
    if (!files.containsKey(required)) {
      stderr.writeln('web build is missing $required, refusing to emit '
          'a bundle that cannot run');
      exit(1);
    }
  }

  final out = StringBuffer()
    ..writeln('// Generated by tool/build_webui.dart from webui/build/web. '
        'Do not edit.')
    ..writeln('//')
    ..writeln('// Maps bundle-relative paths to base64 encoded gzip payloads '
        'so the sync')
    ..writeln('// server can serve the web UI without touching the file '
        'system. An empty')
    ..writeln('// map means the web UI was never built into this copy.')
    ..writeln('const Map<String, String> kWebuiBundle = {');
  final keys = files.keys.toList()..sort();
  for (final rel in keys) {
    final encoded = base64Encode(gzip.encode(files[rel]!));
    out.writeln("  '$rel': '$encoded',");
  }
  out.writeln('};');

  final target = File('${root.path}/lib/server/webui_bundle.dart');
  await target.writeAsString(out.toString());
  final total = files.values.fold<int>(0, (sum, b) => sum + b.length);
  stdout.writeln('Wrote ${target.path} with ${files.length} files '
      '(${(total / 1024 / 1024).toStringAsFixed(1)} MB uncompressed)');
}

bool _include(String rel) {
  if (rel.startsWith('.') || rel.endsWith('.symbols') ||
      rel.endsWith('.map')) {
    return false;
  }
  if (rel == 'flutter_service_worker.js') return false;
  if (rel.startsWith('canvaskit/')) {
    return rel == 'canvaskit/canvaskit.js' ||
        rel == 'canvaskit/canvaskit.wasm' ||
        rel == 'canvaskit/chromium/canvaskit.js' ||
        rel == 'canvaskit/chromium/canvaskit.wasm';
  }
  return true;
}
